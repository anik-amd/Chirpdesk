using System.Diagnostics;
using System.IO;
using System.Net;
using System.Net.Http;
using System.Reflection;
using Chirpdesk.Core.Logging;
using Chirpdesk.Core.Updates;

namespace Chirpdesk.Updates;

internal sealed record UpdateCheckResult(
    bool Available,
    string Message,
    UpdateManifest? Manifest = null)
{
    public string? Version => Manifest?.Version;
}

/// <summary>
/// The network half of the signed updater. Policy stays in Core: this class fetches the stable
/// GitHub release, fetches the signed update.json, verifies it against the pinned key, and only
/// hands back a manifest that passed. Downloads are verified again before launch.
/// </summary>
internal sealed class UpdateService
{
    private const string Repository = "anik-amd/Chirpdesk";
    private const string LatestReleaseUrl = $"https://api.github.com/repos/{Repository}/releases/latest";

    // Generated by scripts/new-update-key.ps1. The private half is deliberately not in this
    // repository. A build with an empty key must refuse every update.
    private const string PublicKey = """
        -----BEGIN PUBLIC KEY-----
        MFkwEwYHKoZIzj0CAQYIKoZIzj0DAQcDQgAEhO0b6APwInGTwrLu2ngelKMYXH+C
        PJGkBMUkSZPep58VLl2qWdbujBUMD8XD7T+IplgCxy7RV5CAaqYCCN2SRw==
        -----END PUBLIC KEY-----
        """;

    private static readonly HttpClient Http = new()
    {
        Timeout = TimeSpan.FromSeconds(30),
    };

    private readonly ILog _log;

    public UpdateService(ILog log) => _log = log;

    public static bool IsConfigured => PublicKey.Contains("BEGIN PUBLIC KEY", StringComparison.Ordinal);

    public async Task<UpdateCheckResult> CheckAsync(CancellationToken cancellationToken = default)
    {
        if (!IsConfigured)
        {
            return new UpdateCheckResult(false, "This build has no pinned update key; updates are refused.");
        }

        try
        {
            using var releaseRequest = new HttpRequestMessage(HttpMethod.Get, LatestReleaseUrl);
            releaseRequest.Headers.UserAgent.ParseAdd($"Chirpdesk/{CurrentVersion()}");
            releaseRequest.Headers.Accept.ParseAdd("application/vnd.github+json");

            using var releaseResponse = await Http.SendAsync(releaseRequest, cancellationToken);
            if (!releaseResponse.IsSuccessStatusCode)
            {
                return releaseResponse.StatusCode switch
                {
                    HttpStatusCode.NotFound => new UpdateCheckResult(
                        false,
                        "No public stable release found. The GitHub repository may be private."),
                    HttpStatusCode.Forbidden or HttpStatusCode.TooManyRequests => new UpdateCheckResult(
                        false,
                        "GitHub rate limit reached. Try again later."),
                    _ => new UpdateCheckResult(false, $"GitHub returned {(int)releaseResponse.StatusCode}."),
                };
            }

            var releaseJson = await releaseResponse.Content.ReadAsStringAsync(cancellationToken);
            if (!GitHubReleaseParser.TryReadLatest(releaseJson, out var release, out var releaseError))
            {
                _log.Warn($"update check: {releaseError}");
                return new UpdateCheckResult(false, releaseError);
            }

            using var manifestResponse = await Http.GetAsync(release!.ManifestUrl, cancellationToken);
            if (!manifestResponse.IsSuccessStatusCode)
            {
                return new UpdateCheckResult(false, $"Update manifest returned {(int)manifestResponse.StatusCode}.");
            }

            var manifestJson = await manifestResponse.Content.ReadAsStringAsync(cancellationToken);
            var manifest = UpdateManifestCodec.TryRead(manifestJson, out var manifestError);
            if (manifest is null)
            {
                _log.Warn($"update check: {manifestError}");
                return new UpdateCheckResult(false, manifestError ?? "update manifest is invalid");
            }

            if (!UpdateVerifier.IsAcceptable(manifest, PublicKey, CurrentVersion(), out var policyError))
            {
                _log.Info($"update check refused: {policyError}");
                return new UpdateCheckResult(false, policyError);
            }

            _log.Info($"update available: {manifest.Version}");
            return new UpdateCheckResult(true, $"Chirpdesk {manifest.Version} is available.", manifest);
        }
        catch (Exception ex) when (ex is HttpRequestException or TaskCanceledException or IOException)
        {
            _log.Warn($"update check failed: {ex.Message}");
            return new UpdateCheckResult(false, "Could not reach GitHub. Try again later.");
        }
    }

    /// <summary>
    /// Downloads the installer named by an already-verified manifest and verifies its exact
    /// size and SHA-256. Returns null when the bytes do not match the signed manifest.
    /// </summary>
    public async Task<string?> DownloadAsync(UpdateManifest manifest, CancellationToken cancellationToken = default)
    {
        if (!UpdateVerifier.IsAbsoluteHttps(manifest.Url, out var urlError))
        {
            _log.Warn($"update download refused: {urlError}");
            return null;
        }

        Directory.CreateDirectory(AppPaths.UpdatesRoot);

        var version = manifest.Version.Replace('/', '-');
        var finalPath = Path.Combine(AppPaths.UpdatesRoot, $"Chirpdesk-Setup-{version}.exe");
        var tempPath = finalPath + ".download";

        try
        {
            if (File.Exists(tempPath))
            {
                File.Delete(tempPath);
            }

            using var response = await Http.GetAsync(manifest.Url, HttpCompletionOption.ResponseHeadersRead, cancellationToken);
            if (!response.IsSuccessStatusCode)
            {
                _log.Warn($"update download: HTTP {(int)response.StatusCode}");
                return null;
            }

            await using (var source = await response.Content.ReadAsStreamAsync(cancellationToken))
            await using (var destination = new FileStream(tempPath, FileMode.CreateNew, FileAccess.Write, FileShare.None))
            {
                var buffer = new byte[81920];
                long total = 0;
                int read;

                while ((read = await source.ReadAsync(buffer, cancellationToken)) > 0)
                {
                    total += read;
                    if (total > manifest.Size)
                    {
                        _log.Warn("update download exceeded the signed size");
                        return null;
                    }

                    await destination.WriteAsync(buffer.AsMemory(0, read), cancellationToken);
                }
            }

            if (!UpdateVerifier.VerifyPayload(manifest, tempPath, out var payloadError))
            {
                _log.Warn($"update download refused: {payloadError}");
                return null;
            }

            if (File.Exists(finalPath))
            {
                File.Delete(finalPath);
            }

            File.Move(tempPath, finalPath);
            _log.Info($"update downloaded and verified: {finalPath}");
            return finalPath;
        }
        catch (Exception ex) when (ex is HttpRequestException or TaskCanceledException or IOException or UnauthorizedAccessException)
        {
            _log.Warn($"update download failed: {ex.Message}");
            return null;
        }
        finally
        {
            TryDelete(tempPath);
        }
    }

    /// <summary>
    /// Starts the verified installer. The app must already have disposed every WebView2
    /// environment; the installer's AppMutex waits for this process to exit.
    /// </summary>
    public bool LaunchInstaller(string path)
    {
        try
        {
            _ = Process.Start(new ProcessStartInfo(path)
            {
                UseShellExecute = true,
                Arguments = "/SILENT /SUPPRESSMSGBOXES /NORESTART /SP- /RELAUNCH",
            });
            _log.Info("update installer started");
            return true;
        }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException or InvalidOperationException)
        {
            _log.Error("could not start the update installer", ex);
            return false;
        }
    }

    /// <summary>Removes partial downloads and installers left from a previous attempt.</summary>
    public void Cleanup()
    {
        if (!Directory.Exists(AppPaths.UpdatesRoot))
        {
            return;
        }

        foreach (var path in Directory.EnumerateFiles(AppPaths.UpdatesRoot))
        {
            TryDelete(path);
        }
    }

    private static Version CurrentVersion() =>
        Assembly.GetEntryAssembly()?.GetName().Version ?? new Version(0, 0, 0, 0);

    private void TryDelete(string path)
    {
        try
        {
            if (File.Exists(path))
            {
                File.Delete(path);
            }
        }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException)
        {
            _log.Warn($"update cleanup could not delete '{Path.GetFileName(path)}'");
        }
    }
}
